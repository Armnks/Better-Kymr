export const frameId = (i) => `FRAME ${String(i + 1).padStart(3, "0")}`;

/** URL slug for a concept. Stable, derived from the authored title. */
export const slugFor = (c) =>
  c.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

/** Look a concept up by slug, or null when the slug is unknown. */
export const conceptBySlug = (slug) => CONCEPTS.find((c) => slugFor(c) === slug) ?? null;
